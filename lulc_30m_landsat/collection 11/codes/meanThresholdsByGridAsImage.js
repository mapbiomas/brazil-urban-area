var cartasWithCutValues = ee.FeatureCollection(
  cartasList.map(function (carta){
    
    var geometryFeature = ee.Feature(cartas.filter(ee.Filter.eq('grid_name', carta)).first())
    
    var infoFeature = ee.Feature(thresholds.filter(ee.Filter.eq('carta', carta)).first())
    
    var threshold = infoFeature.get('threshold'),
        percentil = infoFeature.get('cutPercentile');
    
    return geometryFeature
    .set('threshold', threshold)
    .set('percentil', percentil)
  })
)

// Convert to image for thresholds
